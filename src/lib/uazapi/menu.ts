import type { InteractiveMessagePayload } from '@/lib/whatsapp/interactive'
import type { UazapiMenu } from './api'

// ============================================================
// Our buttons and lists, in UAZAPI's menu format. Pure.
//
// UAZAPI takes one string per choice, with `|` separating the parts:
//   buttons  "Label|id"
//   lists    "[Section]" opens a section, "Label|id|description" a row
//
// The id is what comes back in `buttonOrListid` when the customer taps,
// and flows/automations match on it exactly as they do on Meta's
// button reply id — so ids must survive the trip unchanged. A `|` in a
// label or description would shift the parts, so it becomes `/`. Ids
// are generated by our builders and never contain `|`; if one did, the
// send is refused rather than delivered with a broken id.
//
// UAZAPI buttons have no header line: the header goes on top of the
// body, in bold, so nothing the author wrote is dropped.
// ============================================================

const clean = (s: string) => s.replace(/\|/g, '/').replace(/\s*\n\s*/g, ' ').trim()

function idPart(id: string): string {
  if (id.includes('|') || id.includes('\n')) {
    throw new Error(`id de opção inválido para o WhatsApp não oficial: ${id}`)
  }
  return id
}

function bodyWithHeader(body: string, header?: string): string {
  const h = header?.trim()
  return h ? `*${h}*\n\n${body}` : body
}

export function menuFromInteractive(p: InteractiveMessagePayload): UazapiMenu {
  const footer = p.footer?.trim()
  if (p.kind === 'buttons') {
    return {
      type: 'button',
      text: bodyWithHeader(p.body, p.header),
      choices: p.buttons.map((b) => `${clean(b.title)}|${idPart(b.id)}`),
      ...(footer ? { footerText: footer } : {}),
    }
  }
  const choices: string[] = []
  for (const section of p.sections) {
    const title = section.title?.trim()
    if (title) choices.push(`[${clean(title)}]`)
    for (const row of section.rows) {
      const desc = row.description?.trim()
      choices.push(
        desc
          ? `${clean(row.title)}|${idPart(row.id)}|${clean(desc)}`
          : `${clean(row.title)}|${idPart(row.id)}`,
      )
    }
  }
  return {
    type: 'list',
    text: bodyWithHeader(p.body, p.header),
    choices,
    listButton: clean(p.button_label),
    ...(footer ? { footerText: footer } : {}),
  }
}
